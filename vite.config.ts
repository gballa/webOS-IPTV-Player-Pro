function unwrapCssLayers(css: string): string {
  let result = '';
  let i = 0;
  while (i < css.length) {
    if (css.slice(i, i + 6) === '@layer') {
      const braceIdx = css.indexOf('{', i);
      const semicolonIdx = css.indexOf(';', i);
      if (semicolonIdx !== -1 && (braceIdx === -1 || semicolonIdx < braceIdx)) {
        i = semicolonIdx + 1;
        continue;
      }
      if (braceIdx !== -1) {
        let depth = 1;
        let j = braceIdx + 1;
        while (j < css.length && depth > 0) {
          if (css[j] === '{') depth++;
          else if (css[j] === '}') depth--;
          j++;
        }
        const inner = css.slice(braceIdx + 1, j - 1);
        result += unwrapCssLayers(inner);
        i = j;
        continue;
      }
    }
    result += css[i];
    i++;
  }
  return result;
}

function unwrapPseudo(css: string, pseudo: string): string {
  const target = ':' + pseudo + '(';
  let result = '';
  let i = 0;
  while (i < css.length) {
    const idx = css.indexOf(target, i);
    if (idx === -1) {
      result += css.slice(i);
      break;
    }
    result += css.slice(i, idx);
    let depth = 1;
    let j = idx + target.length;
    while (j < css.length && depth > 0) {
      if (css[j] === '(') depth++;
      else if (css[j] === ')') depth--;
      j++;
    }
    const inner = css.slice(idx + target.length, j - 1);
    result += unwrapPseudo(inner, pseudo);
    i = j;
  }
  return result;
}

function processCssForWebos(rawCss: string): string {
  // 1. Unwrap @layer rules
  let c = unwrapCssLayers(rawCss);

  // 2. Strip RTL language direction selectors generated by Tailwind v4
  c = c.replace(/:not\(:is\(:lang\([^)]+\)(?:,:lang\([^)]+\))*\)\)/g, '');
  c = c.replace(/:not\(:-webkit-any\(:lang\([^)]+\)(?:,:lang\([^)]+\))*\)\)/g, '');

  // 3. Transform group-hover pseudo selectors
  c = c.replace(/([^\s,{]+):is\(:where\(([^)]+)\):hover\s+\*\)/g, '$2:hover $1');

  // 4. Unwrap :where(...) and :is(...) for Chromium 79 compatibility
  c = unwrapPseudo(c, 'where');
  c = unwrapPseudo(c, 'is');

  // 5. Replace :focus-visible with :focus so older browsers do not invalidate entire selector lists
  c = c.replace(/:focus-visible/g, ':focus');

  // 6. Ensure standard box model and transform variables defaults
  const defaults =
    '*,:before,:after,::backdrop{--tw-border-style:solid;--tw-translate-x:0;--tw-translate-y:0;--tw-rotate-x:0;--tw-scale-x:1;--tw-scale-y:1;}';
  c = defaults + '\n' + c;

  // 7. Add -webkit prefixes for backdrop-filter
  c = c.replace(/backdrop-filter:([^;]+);/g, '-webkit-backdrop-filter:$1;backdrop-filter:$1;');

  return c;
}

function webosFileProtocolPlugin() {
  return {
    name: 'webos-file-protocol',
    enforce: 'post' as const,
    generateBundle(_: any, bundle: any) {
      for (const fileName of Object.keys(bundle)) {
        const chunk = bundle[fileName];
        if (chunk.type === 'asset' && fileName.endsWith('.css')) {
          const rawCss = typeof chunk.source === 'string' ? chunk.source : chunk.source.toString('utf8');
          chunk.source = processCssForWebos(rawCss);
        }
      }
    },
    transformIndexHtml(html: string) {
      // 1. Remove modern module scripts which fail on webOS file:// due to strict MIME type checking
      let result = html.replace(/<script type="module"[\s\S]*?<\/script>/gi, '');
      // 2. Remove modulepreload links
      result = result.replace(/<link rel="modulepreload"[\s\S]*?>/gi, '');
      // 3. Remove Safari 10 nomodule shim
      result = result.replace(/<script>!function\(\)\{var e=document[\s\S]*?<\/script>/gi, '');
      // 4. Remove nomodule attribute so legacy SystemJS scripts execute on webOS
      result = result.replace(/<script nomodule/gi, '<script');
      return result;
    },
  };
}

